<#
.SYNOPSIS
  Regenerate the documentation indexes, and optionally check the documentation.

.DESCRIPTION
  Writes two generated files:

  * docs/history/README.md -- one chronological table across every research-line file
    in docs/history/. Entries are the `##` headings; order comes from the stage number
    or date in each heading, never from a list kept here.
  * docs/roadmap/papers/README.md -- every roadmap paper with its frontier targets and
    their status, read from docs/roadmap/frontier.toml.

  With -Check it also fails (exit 1) when
  * a relative Markdown link in the documentation points to a missing file;
  * a frontier.toml target has no existing `paper_file`;
  * a Lean theorem linked from docs/current/papers/ has no statement pin or axiom test
    in ECRuntimeTest/.

  Generated files, like docs/current/graphs/*.mmd: regenerate, never edit by hand.
  Forward slashes throughout, so CI can run it on Linux.

.EXAMPLE
  pwsh -File scripts/docs_index.ps1
  pwsh -File scripts/docs_index.ps1 -Check
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Read-Text([string]$rel) {
    [System.IO.File]::ReadAllText((Join-Path $repo $rel), $utf8) -replace "`r`n", "`n"
}
function Write-Text([string]$rel, [string]$text) {
    [System.IO.File]::WriteAllText((Join-Path $repo $rel), $text, $utf8)
}
function Get-Front([string]$text) {
    $fields = @{}
    if ($text -match '(?s)^---\n(.*?)\n---\n') {
        foreach ($l in ($Matches[1] -split "`n")) {
            if ($l -match '^([a-z_]+):\s*(.*)$') { $fields[$Matches[1]] = $Matches[2].Trim() }
        }
    }
    $fields
}
# GitHub's heading anchors: lower case, punctuation dropped, spaces become hyphens.
function Get-Anchor([string]$heading) {
    (($heading.ToLowerInvariant() -replace '[^\p{L}\p{N} _-]', '') -replace ' ', '-')
}
$months = @{ January = 1; February = 2; March = 3; April = 4; May = 5; June = 6; July = 7;
             August = 8; September = 9; October = 10; November = 11; December = 12 }

# --- history index -------------------------------------------------------------------
$entries = [System.Collections.Generic.List[object]]::new()
$order = 0
# Line files carry `order:` in their front matter, which fixes the order of undated early
# milestones; files without it come last, by name.
$lineFiles = Get-ChildItem (Join-Path $repo 'docs/history') -Filter '*.md' |
    Where-Object Name -ne 'README.md' | ForEach-Object {
        $o = (Get-Front (Read-Text "docs/history/$($_.Name)"))['order']
        [pscustomobject]@{ File = $_; Order = if ($o -match '^\d+$') { [int]$o } else { [int]::MaxValue } }
    } | Sort-Object Order, { $_.File.Name } | ForEach-Object File
foreach ($f in $lineFiles) {
    $text = Read-Text "docs/history/$($f.Name)"
    $line = (Get-Front $text)['line']
    $lastDate = $null
    $seen = @{}
    foreach ($m in [regex]::Matches($text, '(?m)^## (.+)$')) {
        $h = $m.Groups[1].Value.Trim()
        $stage = $null
        if ($h -match 'Stages? (\d+)') { $stage = [int]$Matches[1] }
        $date = $null
        if ($h -match '\((\d{1,2}) ([A-Z][a-z]+) (\d{4})\)' -and $months.ContainsKey($Matches[2])) {
            $date = [datetime]::new([int]$Matches[3], $months[$Matches[2]], [int]$Matches[1])
        } elseif (-not $stage -and $lastDate) { $date = $lastDate }
        if ($date) { $lastDate = $date }
        $anchor = Get-Anchor $h
        if ($seen.ContainsKey($anchor)) { $seen[$anchor]++; $anchor = "$anchor-$($seen[$anchor])" }
        else { $seen[$anchor] = 0 }
        $group = if ($date) { 2 } elseif ($null -ne $stage) { 1 } else { 0 }
        $entries.Add([pscustomobject]@{
            Group = $group; Stage = $stage; Date = $date; Order = $order++
            File = $f.Name; Line = $line; Heading = $h; Anchor = $anchor })
    }
}
$sorted = $entries | Sort-Object Group, @{ Expression = { if ($null -ne $_.Stage) { $_.Stage } else { 0 } } },
                                 @{ Expression = { if ($_.Date) { $_.Date } else { [datetime]::MinValue } } }, Order

$h = [System.Collections.Generic.List[string]]::new()
$h.Add('# History index')
$h.Add('')
$h.Add('<!-- Generated by scripts/docs_index.ps1. Regenerate it; never edit it by hand. -->')
$h.Add('')
$h.Add('Every entry of every research-line file, in chronological order: undated early')
$h.Add('milestones first, then numbered stages, then dated repository events. Stages 80-460 are')
$h.Add('the source checkpoint''s own numbering and have no entries here; stages on `main`')
$h.Add('resume at 461.')
$h.Add('')
$h.Add('Compact mathematical milestones only. Detailed compiler-fix chronology is retained in the')
$h.Add('per-stage verification reviews written to `.verify/stage-<N>/review.txt` by')
$h.Add('`scripts/verify.ps1`, and in archived verification bundles.')
$h.Add('')
$h.Add('| Stage | Date | Line | Entry |')
$h.Add('|---:|---|---|---|')
foreach ($e in $sorted) {
    $st = if ($null -ne $e.Stage) { "$($e.Stage)" } else { '' }
    $dt = if ($e.Date) { $e.Date.ToString('yyyy-MM-dd') } else { '' }
    $title = $e.Heading -replace '\|', '\|'
    $h.Add("| $st | $dt | [``$($e.Line)``]($($e.File)) | [$title]($($e.File)#$($e.Anchor)) |")
}
Write-Text 'docs/history/README.md' (($h -join "`n") + "`n")

# --- roadmap paper index ---------------------------------------------------------------
$toml = Read-Text 'docs/roadmap/frontier.toml'
$targets = @{}
foreach ($blk in ($toml -split '(?m)^\[\[target\]\]\s*$' | Select-Object -Skip 1)) {
    $id = if ($blk -match '(?m)^id = "([^"]+)"') { $Matches[1] } else { continue }
    $targets[$id] = [pscustomobject]@{
        Status = if ($blk -match '(?m)^status = "([^"]+)"') { $Matches[1] } else { '' }
        Paper  = if ($blk -match '(?m)^paper_file = "([^"]+)"') { $Matches[1] } else { '' }
    }
}
$r = [System.Collections.Generic.List[string]]::new()
$r.Add('# Roadmap papers')
$r.Add('')
$r.Add('<!-- Generated by scripts/docs_index.ps1. Regenerate it; never edit it by hand. -->')
$r.Add('')
$r.Add('One file per paper, or per family of results, that the project may formalize next.')
$r.Add('Target ids and their status come from [`frontier.toml`](../frontier.toml); a target id')
$r.Add('without a status is in the Stage-79 frontier survey but not yet in the queue. Papers')
$r.Add('marked *partly certified* also have a file in [`current/papers/`](../../current/papers/).')
$r.Add('')
$r.Add('The Stage-79 frontier survey contained 35 target-result entries spanning 33 papers; its')
$r.Add('introduction and search methodology remain in sections 5 and 6 of the archived')
$r.Add('[`FORMALIZED_RESULTS_AND_LITERATURE_FRONTIER.md`](../../history/archive/FORMALIZED_RESULTS_AND_LITERATURE_FRONTIER.md).')
$r.Add('')
$r.Add('| Paper | Title | Targets | Partly certified |')
$r.Add('|---|---|---|---|')
foreach ($f in (Get-ChildItem (Join-Path $repo 'docs/roadmap/papers') -Filter '*.md' |
                Where-Object Name -ne 'README.md' | Sort-Object Name)) {
    $text = Read-Text "docs/roadmap/papers/$($f.Name)"
    $fm = Get-Front $text
    $title = if ($text -match '(?m)^# (.+)$') { $Matches[1] } else { $f.BaseName }
    $ids = ($fm['targets'] -replace '[\[\]\s]', '') -split ',' | Where-Object { $_ }
    $cells = foreach ($id in $ids) {
        if ($targets.ContainsKey($id)) { "$id ($($targets[$id].Status))" } else { $id }
    }
    $cur = if ($fm['current']) { "[yes]($($fm['current']))" } else { '' }
    $r.Add("| [``$($f.BaseName)``]($($f.Name)) | $($title -replace '\|', '\|') | $($cells -join ', ') | $cur |")
}
Write-Text 'docs/roadmap/papers/README.md' (($r -join "`n") + "`n")
Write-Host "wrote docs/history/README.md ($($entries.Count) entries), docs/roadmap/papers/README.md"

if (-not $Check) { exit 0 }

# --- checks ---------------------------------------------------------------------------
$problems = [System.Collections.Generic.List[string]]::new()

$mdFiles = @(Get-ChildItem (Join-Path $repo 'docs') -Recurse -Filter '*.md') +
           @(Get-ChildItem $repo -Filter '*.md') +
           @(Get-ChildItem (Join-Path $repo '.github') -Recurse -Filter '*.md' -ErrorAction SilentlyContinue)
foreach ($f in $mdFiles) {
    $rel = $f.FullName.Substring($repo.Length).TrimStart('\', '/').Replace('\', '/')
    if ($rel -like 'docs/history/archive/*') { continue }   # frozen: links as they were
    $dir = Split-Path -Parent $f.FullName
    foreach ($m in [regex]::Matches((Read-Text $rel), '\]\(([^)\s]+)\)')) {
        $t = $m.Groups[1].Value
        if ($t -match '^[a-z][a-z0-9+.-]*:' -or $t.StartsWith('#')) { continue }
        $path = ($t -split '#')[0]
        if (-not (Test-Path -LiteralPath (Join-Path $dir $path))) { $problems.Add("broken link in ${rel}: $t") }
    }
}

# Statement approvals: every candidate entry from stage 461 on must record who approved the
# statements and when. Older stages predate the rule and are not checked.
foreach ($f in $lineFiles) {
    $text = Read-Text "docs/history/$($f.Name)"
    foreach ($e in [regex]::Split($text, '(?m)^(?=## )')) {
        if ($e -notmatch '^## (.+)') { continue }
        $h = $Matches[1]
        if ($h -notmatch 'Stages? (\d+)' -or [int]$Matches[1] -lt 461 -or $h -notmatch '(?i)candidate') { continue }
        if ($e -notmatch 'Statements approved by \S.* on \d{4}-\d{2}-\d{2}\.') {
            $problems.Add("history/$($f.Name): '$h' has no 'Statements approved by <maintainer> on <YYYY-MM-DD>.' line")
        }
    }
}

$allIds = [regex]::Matches($toml, '(?m)^id = "([^"]+)"') | ForEach-Object { $_.Groups[1].Value }
foreach ($dup in ($allIds | Group-Object | Where-Object Count -gt 1)) {
    $problems.Add("frontier target id $($dup.Name) is used $($dup.Count) times")
}

# Roadmap paper files (mode 1): key, targets, no template placeholders left.
foreach ($f in Get-ChildItem (Join-Path $repo 'docs/roadmap/papers') -Filter '*.md' | Where-Object Name -ne 'README.md') {
    $text = Read-Text "docs/roadmap/papers/$($f.Name)"
    $fm = Get-Front $text
    if ($fm['paper'] -ne $f.BaseName) { $problems.Add("roadmap/papers/$($f.Name): front matter paper is '$($fm['paper'])', not the file name") }
    $ids = ($fm['targets'] -replace '[\[\]\s]', '') -split ',' | Where-Object { $_ }
    if (-not $ids) { $problems.Add("roadmap/papers/$($f.Name): no targets in front matter") }
    foreach ($id in $ids) {
        if ($targets.ContainsKey($id) -and $targets[$id].Paper -ne "papers/$($f.Name)") {
            $problems.Add("roadmap/papers/$($f.Name): target $id points to $($targets[$id].Paper) in frontier.toml")
        }
    }
    if ($text -match '<first-author>|<target-id>|<Authors>|Template for mode 1') {
        $problems.Add("roadmap/papers/$($f.Name): template placeholders are still present")
    }
}

foreach ($id in $targets.Keys) {
    $p = $targets[$id].Paper
    if (-not $p) { $problems.Add("frontier target $id has no paper_file") }
    elseif (-not (Test-Path -LiteralPath (Join-Path $repo "docs/roadmap/$p"))) {
        $problems.Add("frontier target ${id}: paper_file $p does not exist")
    }
}

$pins = ''; $axioms = ''
foreach ($p in Get-ChildItem (Join-Path $repo 'ECRuntimeTest') -Filter '*.lean') {
    $t = Read-Text "ECRuntimeTest/$($p.Name)"
    if ($p.Name -like '*StatementPins.lean') { $pins += $t }
    if ($p.Name -like '*AxiomAudit.lean') { $axioms += $t }
}
foreach ($f in Get-ChildItem (Join-Path $repo 'docs/current/papers') -Filter '*.md') {
    foreach ($m in [regex]::Matches((Read-Text "docs/current/papers/$($f.Name)"),
                                    '\[`([A-Za-z_][A-Za-z0-9_.'']*)`\]\([^)]*ECRuntime/[A-Za-z0-9_]+\.lean\)')) {
        if ($m.Groups[1].Value -like '*.lean') { continue }   # a module link, not a theorem
        $name = ($m.Groups[1].Value -split '\.')[-1]
        if ($name -match '^[A-Z]') { continue }               # a module name, not a theorem
        $esc = [regex]::Escape($name)
        if ($pins -notmatch "#check @ECRuntime\.(\S+\.)?$esc\b") { $problems.Add("$($f.Name): $name has no statement pin") }
        if ($axioms -notmatch "#print axioms ECRuntime\.(\S+\.)?$esc\b") { $problems.Add("$($f.Name): $name has no axiom test") }
    }
}

$problems = $problems | Sort-Object -Unique
foreach ($p in $problems) { Write-Host "problem: $p" }
if ($problems.Count) { Write-Host "$($problems.Count) documentation problem(s)"; exit 1 }
Write-Host 'documentation checks passed'
exit 0
